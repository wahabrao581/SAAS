
import asyncio
import os
import subprocess

from pathlib import Path

from celery import shared_task
from tortoise import Tortoise


# ==========================================================
# DATABASE INITIALIZATION
# ==========================================================

async def _initialize_database():

    from db_config import TORTOISE_ORM

    await Tortoise.init(
        config=TORTOISE_ORM,
    )


async def _close_database():

    await Tortoise.close_connections()


async def _run_async(coro):

    await _initialize_database()

    try:
        return await coro

    finally:
        await _close_database()


# ==========================================================
# PROCESS GENERATION JOB
# ==========================================================

async def _process_generation_job(job_id):

    from .models import (
        GenerationJob,
        VideoClip,
        JobStatus,
        ClipStatus,
    )

    job = await GenerationJob.get_or_none(
        id=job_id,
    )

    if not job:
        return {
            "status": "not_found",
        }

    if job.status in (
        JobStatus.COMPLETED.value,
        JobStatus.CANCELED.value,
        JobStatus.FAILED.value,
        JobStatus.PARTIAL.value,
    ):
        return {
            "status": "already_finished",
        }

    job.status = JobStatus.PROCESSING.value

    from datetime import datetime, timezone

    if not job.started_at:
        job.started_at = datetime.now(timezone.utc)

    await job.save()

    clips = await VideoClip.filter(
        job_id=job.id,
    ).order_by("sequence")

    dispatched = 0

    # Provider application owns GPU dispatch.
    from apps.providers.celery import generate_clip_task

    for clip in clips:

        if clip.status not in (
            ClipStatus.PENDING.value,
            ClipStatus.QUEUED.value,
        ):
            continue

        clip.status = ClipStatus.QUEUED.value

        await clip.save(
            update_fields=["status", "updated_at"],
        )

        generate_clip_task.delay(
            str(clip.id)
        )

        dispatched += 1

    return {
        "job_id": str(job.id),
        "status": "dispatched",
        "dispatched_clips": dispatched,
    }


@shared_task(
    name="prompting.process_generation_job",
    bind=True,
    max_retries=3,
    default_retry_delay=30,
)
def process_generation_job(
    self,
    job_id,
):

    try:

        return asyncio.run(
            _run_async(
                _process_generation_job(job_id)
            )
        )

    except Exception as exc:

        raise self.retry(exc=exc)


# ==========================================================
# VIDEO ASSEMBLY
# ==========================================================

async def _assemble_video(
    job_id,
    clip_ids,
):

    from .models import (
        GenerationJob,
        VideoClip,
        VideoProject,
        ClipStatus,
        JobStatus,
    )

    from .services import complete_video_assembly

    job = await GenerationJob.get_or_none(
        id=job_id,
    )

    if not job:
        raise ValueError("Generation job not found.")

    clips = await VideoClip.filter(
        id__in=clip_ids,
        job_id=job.id,
        status=ClipStatus.COMPLETED.value,
    ).order_by("sequence")

    if not clips:
        raise ValueError(
            "No completed clips available."
        )

    if len(clips) != len(set(clip_ids)):
        raise ValueError(
            "One or more requested clips are unavailable."
        )

    media_root = Path(
        os.getenv("MEDIA_ROOT", "./media")
    ).resolve()

    output_directory = (
        media_root
        / "projects"
        / str(job.project_id)
        / str(job.id)
    ).resolve()

    output_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Prevent path traversal.
    if media_root not in output_directory.parents:
        raise ValueError("Invalid output directory.")

    input_files = []

    for clip in clips:

        if not clip.output_storage_key:
            raise ValueError(
                f"Clip {clip.id} has no stored output."
            )

        input_path = (
            media_root / clip.output_storage_key
        ).resolve()

        if media_root not in input_path.parents:
            raise ValueError("Invalid clip storage path.")

        if not input_path.is_file():
            raise FileNotFoundError(
                f"Clip file missing: {clip.id}"
            )

        input_files.append(input_path)

    concat_file = output_directory / "concat.txt"

    output_file = output_directory / "final_video.mp4"

    # FFmpeg concat demuxer manifest.
    # Paths are generated by the server, not accepted from clients.
    with concat_file.open("w", encoding="utf-8") as file:

        for path in input_files:

            escaped = str(path).replace("'", "'\\''")

            file.write(
                f"file '{escaped}'\n"
            )

    command = [
        "ffmpeg",
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-f",
        "concat",
        "-safe",
        "0",
        "-i",
        str(concat_file),
        "-c",
        "copy",
        str(output_file),
    ]

    result = subprocess.run(
        command,
        capture_output=True,
        text=True,
        timeout=7200,
        check=False,
    )

    if result.returncode != 0:

        raise RuntimeError(
            result.stderr[-4000:]
        )

    relative_key = str(
        output_file.relative_to(media_root)
    )

    media_base_url = os.getenv(
        "MEDIA_BASE_URL",
        "",
    ).rstrip("/")

    output_url = (
        f"{media_base_url}/{relative_key}"
        if media_base_url
        else None
    )

    project = await complete_video_assembly(
        job_id=job.id,
        output_url=output_url,
        storage_key=relative_key,
    )

    concat_file.unlink(
        missing_ok=True,
    )

    return {
        "job_id": str(job.id),
        "project_id": str(project.id),
        "output_key": relative_key,
        "output_url": output_url,
        "status": "completed",
    }


@shared_task(
    name="prompting.assemble_video",
    bind=True,
    max_retries=2,
    default_retry_delay=60,
)
def assemble_video_task(
    self,
    job_id,
    clip_ids,
):

    try:

        return asyncio.run(
            _run_async(
                _assemble_video(
                    job_id,
                    clip_ids,
                )
            )
        )

    except Exception as exc:

        raise self.retry(exc=exc)


