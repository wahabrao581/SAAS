# PROJECT CLEANUP
# ==========================================================

async def _cleanup_archived_projects():

    from .models import VideoProject

    # This task only reports archived projects.
    # Actual file deletion must be coordinated with
    # storage retention and account deletion policies.

    return await VideoProject.filter(
        status="archived",
    ).count()


@shared_task(
    name="prompting.cleanup_archived_projects",
)
def cleanup_archived_projects_task():

    return asyncio.run(
        _run_async(
            _cleanup_archived_projects()
        )
    )
